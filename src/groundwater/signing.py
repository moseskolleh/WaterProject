#: What a signed statement's file says it is, and the version of its layout.
SIGNED_FORMAT = "groundwater-toolkit signed statement"
#: What an organisation's file of its members' keys says it is.
MEMBERS_FORMAT = "groundwater-toolkit members' keys"
FORMAT_VERSION = 1

#: The largest whole number a statement holds. Above it the two engines'
#: readers stop agreeing (JavaScript's numbers stop being exact at 2**53),
#: and nothing a statement counts comes near it.
MAX_NUMBER = 999_999_999
#: The longest text of a statement, a signed statement or a members' file,
#: in bytes: a file far past what the toolkit writes is not read.
MAX_BYTES = 200_000

_NAME = re.compile(r"^[a-z][a-z0-9_]{0,39}\Z")
_KEY = re.compile(r"^04[0-9a-f]{128}\Z")
_SIGNATURE = re.compile(r"^[0-9a-f]{128}\Z")
_KEY_ID = re.compile(r"^[0-9a-f]{64}\Z")


# ---------------------------------------------------------------------------
# The curve
# ---------------------------------------------------------------------------

# NIST P-256 (secp256r1): y^2 = x^3 - 3x + b over the field of _P, with a
# group of prime order _N generated by (_GX, _GY). FIPS 186-4, D.1.2.3.
_P = 0xFFFFFFFF00000001000000000000000000000000FFFFFFFFFFFFFFFFFFFFFFFF
_N = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551
_B = 0x5AC635D8AA3A93E7B3EBBD55769886BC651D06B0CC53B0F63BCE3C3E27D2604B
_GX = 0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296
_GY = 0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5


def _add(a, b):
    """The sum of two points of the curve; None is the point at infinity."""
    if a is None:
        return b
    if b is None:
        return a
    (x1, y1), (x2, y2) = a, b
    if x1 == x2:
        if (y1 + y2) % _P == 0:
            return None
        slope = (3 * x1 * x1 - 3) * pow(2 * y1, -1, _P) % _P
    else:
        slope = (y2 - y1) * pow(x2 - x1, -1, _P) % _P
    x3 = (slope * slope - x1 - x2) % _P
    return x3, (slope * (x1 - x3) - y1) % _P


def _times(k: int, point):
    """``k`` times a point, by doubling and adding."""
    total = None
    while k:
        if k & 1:
            total = _add(total, point)
        point = _add(point, point)
        k >>= 1
    return total


def verify_p256(key: Any, message: bytes, signature: Any) -> bool:
    """Whether ``signature`` (128 hexadecimal digits, ``r || s``) is the
    ECDSA P-256 / SHA-256 signature of ``message`` under the public ``key``
    (130 hexadecimal digits: ``04``, x, y). False for anything that is not a
    key on the curve or not a signature in range, never an error."""
    if not (isinstance(key, str) and _KEY.match(key)
            and isinstance(signature, str) and _SIGNATURE.match(signature)
            and isinstance(message, (bytes, bytearray))):
        return False
    x, y = int(key[2:66], 16), int(key[66:], 16)
    # a point that is not on the curve is not a key: without this check a
    # made-up point can be chosen to pass for any message
    if x >= _P or y >= _P or (y * y - (x * x * x - 3 * x + _B)) % _P:
        return False
    r, s = int(signature[:64], 16), int(signature[64:], 16)
    if not (1 <= r < _N and 1 <= s < _N):
        return False
    digest = int.from_bytes(hashlib.sha256(bytes(message)).digest(), "big")
    w = pow(s, -1, _N)
    point = _add(_times(digest * w % _N, (_GX, _GY)), _times(r * w % _N, (x, y)))
    return point is not None and point[0] % _N == r


def key_id(key: Any) -> str:
    """What a statement calls a key: the SHA-256 of the public point's 65
    bytes, as hexadecimal. Blank for anything that is not a key."""
    if not (isinstance(key, str) and _KEY.match(key)):
        return ""
    return hashlib.sha256(bytes.fromhex(key)).hexdigest()


def key_code(identifier: Any) -> str:
    """A key's identifier as people read it out: its first 80 bits, in five
    groups of four. Long enough that nobody can make a second key to match
    it, short enough to compare by voice."""
    if not (isinstance(identifier, str) and _KEY_ID.match(identifier)):
        return ""
    head = identifier[:20].upper()
    return "-".join(head[i:i + 4] for i in range(0, 20, 4))


# ---------------------------------------------------------------------------
# The text of a statement
# ---------------------------------------------------------------------------

def _refuse_constant(token: str):
    raise ValueError(token)


def _clean_text(value) -> bool:
    return isinstance(value, str) and _text(value) == value


def _whole(value) -> bool:
    return isinstance(value, int) and not isinstance(value, bool) and 0 <= value <= MAX_NUMBER


def clean_statement(value: Any) -> dict | None:
    """``value`` if it is a statement as this module writes one, else None:
    named values, ``says`` first and not blank, each a clean text, a whole
    number in range, a list of clean texts, or named clean texts."""
    if not isinstance(value, dict) or not value or next(iter(value)) != "says":
        return None
    if not (_clean_text(value["says"]) and value["says"]):
        return None
    for name, item in value.items():
        if not (isinstance(name, str) and _NAME.match(name)):
            return None
        if _clean_text(item) or _whole(item):
            continue
        if isinstance(item, list) and all(_clean_text(entry) for entry in item):
            continue
        if isinstance(item, dict) and all(
                isinstance(key, str) and _NAME.match(key) and _clean_text(entry)
                for key, entry in item.items()):
            continue
        return None
    return value


def _written(value: dict) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False) + "\n"


def statement_text(statement: Any) -> str:
    """The text of a statement: what is signed, byte for byte, in both
    engines. Raises ValueError for anything that is not a statement, since a
    text that cannot be read back must not be signed."""
    if clean_statement(statement) is None:
        raise ValueError("signing: this is not a statement the toolkit writes")
    return _written(statement)


def _loaded(text: Any):
    """What a JSON text holds, or None for anything this module would not
    have written: not text, too long, not UTF-8, not JSON."""
    if not isinstance(text, str):
        return None
    try:
        if len(text.encode("utf-8")) > MAX_BYTES:
            return None
        return json.loads(text, parse_constant=_refuse_constant)
    except (ValueError, RecursionError):
        return None


def read_statement(text: Any) -> dict | None:
    """The statement a text holds, or None unless the text is exactly what
    :func:`statement_text` writes for it."""
    statement = clean_statement(_loaded(text))
    return statement if statement is not None and _written(statement) == text else None


# ---------------------------------------------------------------------------
# A signed statement
# ---------------------------------------------------------------------------

def signed_text(statement: Any, key: Any, signature: Any) -> str:
    """The file a signed statement is kept in: what it is, the statement,
    the public key and the signature. Raises ValueError for a statement,
    key or signature that is not one."""
    if clean_statement(statement) is None:
        raise ValueError("signing: this is not a statement the toolkit writes")
    if not (isinstance(key, str) and _KEY.match(key)):
        raise ValueError("signing: this is not a public key")
    if not (isinstance(signature, str) and _SIGNATURE.match(signature)):
        raise ValueError("signing: this is not a signature")
    return _written({"format": SIGNED_FORMAT, "version": FORMAT_VERSION,
                     "statement": statement, "key": key, "signature": signature})


def read_signed(text: Any) -> dict | None:
    """What a signed statement's file holds (``statement``, ``key``,
    ``signature``), or None unless the text is exactly what
    :func:`signed_text` writes. Reading says nothing of whether the
    signature holds: :func:`check_signed` does."""
    held = _loaded(text)
    if not isinstance(held, dict) or list(held) != ["format", "version", "statement", "key",
                                                    "signature"]:
        return None
    if held["format"] != SIGNED_FORMAT or held["version"] != FORMAT_VERSION or isinstance(
            held["version"], bool):
        return None
    try:
        again = signed_text(held["statement"], held["key"], held["signature"])
    except ValueError:
        return None
    if again != text:
        return None
    return {"statement": held["statement"], "key": held["key"], "signature": held["signature"]}


# ---------------------------------------------------------------------------
# The organisation's members
# ---------------------------------------------------------------------------

_MEMBER = ("name", "role", "key", "valid_from", "valid_to", "withdrawn")


def _day_or_blank(value) -> bool:
    if value == "":
        return True
    day = iso_date(value) if isinstance(value, str) else None
    return day is not None and day.isoformat() == value


def _clean_members(value: Any) -> dict | None:
    if not isinstance(value, dict) or list(value) != ["format", "version", "organisation",
                                                      "issued_on", "members"]:
        return None
    if value["format"] != MEMBERS_FORMAT or value["version"] != FORMAT_VERSION or isinstance(
            value["version"], bool):
        return None
    # a list with no organisation's name on it is nobody's list
    if not (_clean_text(value["organisation"]) and value["organisation"]):
        return None
    if not (value["issued_on"] != "" and _day_or_blank(value["issued_on"])):
        return None
    members = value["members"]
    if not isinstance(members, list):
        return None
    seen = set()
    for member in members:
        if not isinstance(member, dict) or tuple(member) != _MEMBER:
            return None
        if not (_clean_text(member["name"]) and member["name"] and _clean_text(member["role"])):
            return None
        if not (isinstance(member["key"], str) and _KEY.match(member["key"])):
            return None
        # a date that is not one is not read as "no date": the file is refused
        if not all(_day_or_blank(member[field]) for field in ("valid_from", "valid_to",
                                                              "withdrawn")):
            return None
        # one key, one member: listed twice, which of the two is it?
        if member["key"] in seen:
            return None
        seen.add(member["key"])
    return value


def members_text(members: Any) -> str:
    """The text of an organisation's file of its members' keys. Raises
    ValueError for anything that is not one."""
    if _clean_members(members) is None:
        raise ValueError("signing: this is not a members' file the toolkit writes")
    return _written(members)


def read_members(text: Any) -> dict | None:
    """What a members' file holds, or None unless the text is exactly what
    :func:`members_text` writes: a name for the organisation, the day the
    list was issued, and for each member a name, a role, a key and three
    days that are each a day or blank (valid from, valid to, withdrawn)."""
    members = _clean_members(_loaded(text))
    return members if members is not None and _written(members) == text else None


def members_code(text: Any) -> str:
    """The code a members' file is known by: of the SHA-256 of its text, the
    first 80 bits in five groups of four. Whoever is handed the file compares
    this with the one the organisation gives out, by voice or on paper."""
    if read_members(text) is None:
        return ""
    return key_code(hashlib.sha256(text.encode("utf-8")).hexdigest())


def signer_standing(members: Any, identifier: Any, day: Any = "") -> dict:
    """Where a key stands in a members' file, on ``day`` (the day the
    statement says it was signed).

    ``standing`` is ``not_checked`` with no file; ``not_listed``; ``withdrawn``
    for a key the organisation has withdrawn, whatever day the statement
    claims, since that day is the signer's own clock; ``out_of_dates`` for a
    statement dated outside the days the key is valid for, or not dated at
    all where the key has such days; else ``listed``. ``member`` is the
    member's entry where the key is in the file.
    """
    if _clean_members(members) is None:
        return {"standing": "not_checked", "member": None}
    member = next((m for m in members["members"] if key_id(m["key"]) == identifier), None)
    if member is None:
        return {"standing": "not_listed", "member": None}
    if member["withdrawn"]:
        return {"standing": "withdrawn", "member": member}
    if member["valid_from"] or member["valid_to"]:
        on = day if isinstance(day, str) and _day_or_blank(day) else ""
        if (not on or (member["valid_from"] and on < member["valid_from"])
                or (member["valid_to"] and on > member["valid_to"])):
            return {"standing": "out_of_dates", "member": member}
    return {"standing": "listed", "member": member}


# ---------------------------------------------------------------------------
# Checking
# ---------------------------------------------------------------------------

def check_signed(text: Any, members_file: Any = None) -> dict:
    """Check a signed statement's file, and its signer against a members'
    file where one is given (its text).

    Returns ``verdict``: ``not_a_statement`` for a text that is not a signed
    statement the toolkit wrote; ``does_not_hold`` where the signature is
    not the named key's over this text, or the statement names another key;
    else ``holds``. With it: the ``statement``, the ``key`` identifier and
    its ``code``, the signer's ``standing`` and ``member`` (see
    :func:`signer_standing`), the members' file's ``file_code``, and
    ``lines``, what to tell a person, in the words both apps use.
    """
    out: dict[str, Any] = {"verdict": "not_a_statement", "statement": None, "key": "",
                           "code": "", "standing": "not_checked", "member": None,
                           "file_code": "", "lines": []}
    signed = read_signed(text)
    if signed is None:
        out["lines"] = [phrase("signing.not_a_statement")]
        return out
    statement = signed["statement"]
    identifier = key_id(signed["key"])
    out.update(statement=statement, key=identifier, code=key_code(identifier))
    # the statement names its key, so that the signature binds the key: a
    # second key under which the same signature happened to verify could
    # not claim the statement
    if statement.get("key") != identifier or not verify_p256(
            signed["key"], _written(statement).encode("utf-8"), signed["signature"]):
        out["verdict"] = "does_not_hold"
        out["lines"] = [phrase("signing.does_not_hold")]
        return out
    out["verdict"] = "holds"
    lines = [phrase("signing.holds", code=out["code"])]
    at = statement.get("at")
    if isinstance(at, str) and at:
        lines.append(phrase("signing.time_is_a_claim", at=at))
    members = read_members(members_file) if members_file is not None else None
    if members_file is not None and members is None:
        lines.append(phrase("signing.members_unreadable"))
    elif members is None:
        lines.append(phrase("signing.standing_not_checked"))
    else:
        day = at[:10] if isinstance(at, str) else ""
        placed = signer_standing(members, identifier, day)
        out.update(standing=placed["standing"], member=placed["member"],
                   file_code=members_code(members_file))
        given = {"organisation": members["organisation"], "file": out["file_code"]}
        member = placed["member"]
        if member is None:
            lines.append(phrase("signing.standing_not_listed", **given))
        else:
            sentence = {"listed": "signing.standing_listed",
                        "withdrawn": "signing.standing_withdrawn",
                        "out_of_dates": "signing.standing_out_of_dates"}[placed["standing"]]
            lines.append(phrase(sentence, name=member["name"],
                                role=member["role"] or phrase("signing.no_role"), **given))
    out["lines"] = lines
    return out
