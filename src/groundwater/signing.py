"""Signed statements (PLAN.md step 8.2): what a person decided, in a text
that can be checked against their key by anyone, with no network.

A sign-off and a readiness override used to be a name somebody typed. A
*signed statement* is a small text saying what one person decided, on which
figures, with a signature over that exact text made by the key only they
hold. This module is the part both engines share and neither needs a
browser for: how a statement is written so that both engines write the same
bytes, how it is read back (strictly: a text the toolkit did not write is not
read at all), how a signature over it is checked, and how a signer is placed
against the list of keys an organisation publishes. ``gwt-core.js`` has the
same rules in ``585-signing.js``, held to these by the parity suite.

**Signing is done in the browser app, with Web Crypto.** Nothing here makes a
signature or holds a private key, and nothing here can: a key made by Web
Crypto does not leave the device it was made on except as the passphrase-
protected backup its owner saves. What this module does is verify.

What a signature shows, and what it does not
--------------------------------------------

- It shows that the holder of a key approved exactly this text. The text
  names the key, so no other key can claim it.
- It does not show who holds the key. That is what the organisation's
  members' file is for: a signer is "listed" when their key is in the file
  the checker was given, in date and not withdrawn. The file is only as
  good as the way the checker came by it.
- The time in a statement is the signer's own device's. It is a claim.
- It does not show that a document quoting the statement is the toolkit's
  own or unchanged: that is the document's manifest and its issue record
  (``verification.py``).

The text
--------

A statement is a JSON object whose first key is ``says``, with values that
are text, whole numbers from 0 to 999,999,999, lists of text, or one level
of named text (the figures a person approved). It is written exactly as
``manifest.json`` is (``bundle.bundle_manifest``): two-space indents, keys in
the order given, text as it is, a newline at the end. There are no decimal
numbers in it, which is where the two engines' writers differ; a figure is
written as the text the person saw. Every text is cleaned as a manifest's
is. A reader accepts a text only if writing what it read gives the same
text again.

The signature is ECDSA over P-256 with SHA-256, the 64 bytes ``r || s``
that Web Crypto makes, as 128 hexadecimal digits. The key is the public
point, uncompressed (``04``, x, y), as 130 hexadecimal digits. The check is
written out here with whole-number arithmetic and the standard library's
SHA-256, as the QR encoder's field arithmetic is: the package gains no
dependency, and the check runs wherever Python does. It is verification
only, of public values, so it need not run in constant time.
"""

