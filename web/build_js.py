"""Join the source parts of the three large browser scripts.

``docs/js/gwt-core.js`` is forty thousand lines, ``gwt-app.js`` ten
thousand and ``gwt-charts.js`` seven thousand. Each is one closure: the
sections of the engine name each other's functions bare, several hundred
times over, so they cannot be made into separate scripts without
changing what the browser runs. But a file that size cannot be read, and
a change to it cannot be reviewed: the diff of one hydraulics fix sits
in the same file as the QR encoder and the GeoTIFF reader.

So the three are written as parts and joined here. The parts of
``docs/js/<name>.js`` are the files of ``web/src/<name>/``, one for each
banner section of the script: one Python module's port in the engine,
one page in the app, one family of figures in the charts. They are named
``NNN-name.js`` and joined in the order of their numbers, which go up in
tens so that a part can be added between two others. A part is not a
script and need not parse alone: the first opens the closure and the
last closes it.

The join is a concatenation and nothing else. No byte is added between
two parts, nothing is transformed, minified or wrapped, and the bytes
are read and written as bytes, so the browser still runs exactly the
text a person wrote. That is also why the joined file is still what is
committed: ``docs/js/<name>.js`` is what GitHub Pages serves, what the
service worker precaches, what ``web/build_webapp_data.py`` hashes into
the engine digest, and what every test, tsc and oxlint read. Only this
script, and the tests that hold it, read ``web/src``. Edit the parts,
run this, and commit the join with them; ``tests/test_web_build.py``
and ``nox -s bundles`` fail a joined file that is not the join of its
parts, which is what an edit made to ``docs/js`` directly looks like,
and the next run of this script would overwrite such an edit. The other
scripts in ``docs/js`` have no parts and are edited where they are.

Run from the repository root, before ``web/build_webapp_data.py`` (the
engine digest in ``gwt-data.js`` is a hash of ``gwt-core.js``):

    python web/build_js.py                  # join the parts into docs/js
    python web/build_js.py --check          # verify them, don't rewrite
    python web/build_js.py --where docs/js/gwt-core.js:12345
                                            # the part a line comes from

tsc, oxlint and a browser's stack trace all give a line of the joined
file, because that is the file they were given. ``--where`` turns it
into the part and the line within it, and takes the forms those tools
print: ``gwt-core.js:12345``, ``docs/js/gwt-core.js:12345:7`` and tsc's
``docs/js/gwt-core.js(12345,7)``.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "web" / "src"
OUT = REPO / "docs" / "js"

# The scripts that are joined from parts. Each has a folder under web/src
# named for it without the extension. Every other script in docs/js is
# either small enough to read whole or generated by another builder.
BUNDLES = ("gwt-core.js", "gwt-app.js", "gwt-charts.js")

# A part's file name. The three digits are its place in the join, and the
# pattern is strict because the order is the file's meaning: "15-x.js" sorts
# after "140-y.js", and a stray "010-config.js.orig" is somebody's edit that
# would otherwise be silently left out of the script.
PART = re.compile(r"(\d{3})-[a-z0-9]+(?:-[a-z0-9]+)*\.js")

# What --where accepts: an optional path, a bundle name, then the line (and
# perhaps a column) as oxlint and browsers write it or as tsc does.
WHERE = re.compile(
    r"(?:.*[/\\])?(?P<name>[^/\\:()]+\.js)"
    r"(?::(?P<line>\d+)(?::(?P<col>\d+))?|\((?P<tline>\d+),(?P<tcol>\d+)\))"
)


class PartsError(Exception):
    """The parts of a script cannot be joined as they stand."""


def _shown(path: Path) -> str:
    """A path as a message names it: from the repository root where it can be."""
    try:
        return path.resolve().relative_to(REPO).as_posix()
    except ValueError:
        return str(path)


def parts(bundle: str, src: Path = SRC) -> list[Path]:
    """The parts of one script, in the order they are joined.

    The order is the file names', compared as text, which for names that
    all begin with three digits is the order of the numbers and is the same
    on every machine: no locale and no directory order comes into it.

    Everything the join relies on is checked here, so that it is refused
    with the file's name rather than found later as a script that will not
    parse. A name that is not ``NNN-name.js`` is refused, as is a number
    two parts share, since the number is the order. An empty part is
    refused, and so is one that does not end with a newline: a cut falls
    at the start of a line, which is what lets ``--where`` name one part
    for every line of the joined file. Files whose names begin with a dot
    are passed over: they are what an operating system or an editor leaves
    in a folder it has shown (``.DS_Store`` is in ``.gitignore``), git does
    not carry them, and none can be mistaken for a part.
    """
    folder = src / bundle[: -len(".js")]
    if not folder.is_dir():
        raise PartsError(f"{_shown(folder)} is missing: {bundle} has no parts to join")
    found: list[Path] = []
    numbers: dict[str, str] = {}
    for name in sorted(entry.name for entry in folder.iterdir()):
        if name.startswith("."):
            continue
        path = folder / name
        match = PART.fullmatch(name)
        if not match or not path.is_file():
            raise PartsError(
                f"{_shown(path)} is not a part: the parts of {bundle} are files "
                "named NNN-name.js (three digits, then lower-case words joined "
                "by hyphens), and nothing else may sit beside them"
            )
        if match.group(1) in numbers:
            raise PartsError(
                f"{_shown(path)} and {numbers[match.group(1)]} share the number "
                f"{match.group(1)}: the number is a part's place in {bundle}, "
                "so each part needs one of its own"
            )
        numbers[match.group(1)] = name
        data = path.read_bytes()
        if not data:
            raise PartsError(f"{_shown(path)} is empty")
        if not data.endswith(b"\n"):
            raise PartsError(
                f"{_shown(path)} does not end with a newline, so its last line "
                "would run into the first line of the next part"
            )
        found.append(path)
    if not found:
        raise PartsError(f"{_shown(folder)} holds no parts")
    return found


def join(bundle: str, src: Path = SRC) -> bytes:
    """One script as its parts make it: their bytes, end to end."""
    return b"".join(path.read_bytes() for path in parts(bundle, src))


def locate(bundle: str, line: int, src: Path = SRC) -> tuple[Path, int]:
    """The part a line of the joined script comes from, and its line there.

    Lines are counted from 1 and end at a newline, as tsc, oxlint and the
    browsers count them.
    """
    if line < 1:
        raise PartsError(f"{bundle} has no line {line}: lines are counted from 1")
    before = 0
    for path in parts(bundle, src):
        length = path.read_bytes().count(b"\n")
        if line <= before + length:
            return path, line - before
        before += length
    raise PartsError(f"{bundle} has no line {line}: its parts join to {before} lines")


def first_difference(joined: bytes, committed: bytes) -> int | None:
    """The first line at which two texts differ, or None where they are one.

    Where one is the other with lines added at its end, it is the first of
    the added lines; where they differ only in a last line's newline, it is
    that line.
    """
    if joined == committed:
        return None
    ours, theirs = joined.split(b"\n"), committed.split(b"\n")
    shorter = min(len(ours), len(theirs))
    for index in range(shorter):
        if ours[index] != theirs[index]:
            return index + 1
    # One list is the start of the other, so the shorter text's last piece,
    # which no newline follows, is where the longer one goes on.
    return shorter


def _line_text(data: bytes, line: int) -> str:
    """One line of a text as a message quotes it, or that it has no such line."""
    lines = data.split(b"\n")
    # a text that ends with a newline splits into its lines and one empty tail
    count = len(lines) - 1 if data.endswith(b"\n") else len(lines)
    if line > count:
        return f"(nothing: it ends at line {count})"
    text = lines[line - 1].decode("utf-8", errors="replace")
    text = text if len(text) <= 100 else text[:97] + "..."
    return text if line < len(lines) else text + "  (no newline after it)"


def _same_to_the_eye(joined: bytes, committed: bytes, line: int) -> str:
    """What separates two lines that are quoted alike: a carriage return, a
    trailing space, or a change past where a long line is cut short. Without
    it the message shows the same text twice and says they differ."""
    ours = joined.split(b"\n")[line - 1]
    theirs = committed.split(b"\n")[line - 1]
    column = next((k for k, (a, b) in enumerate(zip(ours, theirs, strict=False)) if a != b),
                  min(len(ours), len(theirs)))
    return (f"  They differ from column {column + 1}: the parts have "
            f"{ours[column:column + 24]!r} there, the committed file "
            f"{theirs[column:column + 24]!r}.\n")


def explain(bundle: str, joined: bytes, committed: bytes, src: Path = SRC,
            out: Path = OUT) -> str:
    """Why a committed script is not the join of its parts, for a person.

    Names the first line that differs and the part it comes from, and
    quotes both versions of it, because the two usual causes need different
    cures: a part was edited and the join not run, or the joined file was
    edited and the change has to be moved into the part.
    """
    line = first_difference(joined, committed)
    target = _shown(out / bundle)
    if line is None:
        return f"{target} is the join of its parts"
    try:
        path, within = locate(bundle, line, src)
        origin = f"which is line {within} of {_shown(path)}"
    except PartsError:
        origin = (f"which is past the end of the last part, "
                  f"{_shown(parts(bundle, src)[-1])}")
    ours, theirs = _line_text(joined, line), _line_text(committed, line)
    alike = ours.rstrip() == theirs.rstrip()
    note = _same_to_the_eye(joined, committed, line) if alike else ""
    return (
        f"{target} is not the join of its parts. The first difference is at "
        f"line {line},\n{origin}:\n"
        f"  parts:     {ours}\n"
        f"  committed: {theirs}\n"
        f"{note}"
        f"The parts are the source. If {target} was edited by hand, make the "
        "change in the part\ninstead; then join them with:\n"
        "  python web/build_js.py"
    )


def write_atomically(path: Path, data: bytes) -> None:
    """Replace ``path`` in one step, or leave what is there untouched.

    As ``web/build_offline.py`` writes the service worker, and for the same
    reason: these are the scripts the site serves, and one cut short half
    way through a write is an app that does not start.
    """
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_bytes(data)
    os.replace(tmp, path)


def _where(reference: str, src: Path, out: Path) -> str:
    """The answer to one ``--where`` reference: ``part:line`` or ``part:line:col``."""
    match = WHERE.fullmatch(reference.strip())
    if not match:
        raise PartsError(
            f"cannot read {reference!r} as a line of a script: write it as "
            "docs/js/gwt-core.js:12345, as oxlint and a browser do, or as "
            "docs/js/gwt-core.js(12345,7), as tsc does"
        )
    name = match.group("name")
    if name not in BUNDLES:
        raise PartsError(
            f"{name} is not joined from parts ({', '.join(BUNDLES)} are): "
            "the line is its own, in docs/js"
        )
    line = int(match.group("line") or match.group("tline"))
    column = match.group("col") or match.group("tcol")
    path, within = locate(name, line, src)
    committed = out / name
    if committed.exists() and committed.read_bytes() != join(name, src):
        # The line was read off the committed file; the parts are what is
        # being searched. Where the two have parted company the answer can
        # be wrong from the first difference down, and saying nothing would
        # send someone to the right part and the wrong line.
        print(
            f"note: {_shown(committed)} is not the join of its parts as they "
            "stand, so a line taken from it may map\nwrongly below the first "
            "difference. python web/build_js.py --check says where that is.",
            file=sys.stderr,
        )
    return f"{_shown(path)}:{within}" + (f":{column}" if column else "")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--check", action="store_true",
        help="compare the committed scripts against a fresh join instead of "
             "rewriting them; exit non-zero, naming the first differing line "
             "and the part it comes from, if one is not the join of its parts",
    )
    mode.add_argument(
        "--where", nargs="+", metavar="FILE:LINE",
        help="print the part, and the line within it, that a line of a "
             "joined script comes from, for example docs/js/gwt-core.js:12345",
    )
    parser.add_argument(
        "--src", default=str(SRC), metavar="DIR",
        help="the folder holding one folder of parts for each script "
             "(default: web/src)",
    )
    parser.add_argument(
        "--out", default=str(OUT), metavar="DIR",
        help="the folder the joined scripts are written to, or checked in "
             "(default: docs/js)",
    )
    args = parser.parse_args(argv)
    src, out = Path(args.src), Path(args.out)

    try:
        if args.where:
            for reference in args.where:
                print(_where(reference, src, out))
            return 0

        # Every script is joined before any is written or judged, so a parts
        # folder that cannot be joined is reported beside the others' verdicts
        # and a run that refuses one script has not half-written the rest.
        joins: dict[str, tuple[int, bytes]] = {}
        refused = 0
        for bundle in BUNDLES:
            try:
                pieces = parts(bundle, src)
            except PartsError as exc:
                print(f"error: {exc}", file=sys.stderr)
                refused += 1
                continue
            joins[bundle] = (len(pieces), b"".join(p.read_bytes() for p in pieces))
        if refused and not args.check:
            print("nothing written", file=sys.stderr)
            return 1

        stale = 0
        for bundle, (count, joined) in joins.items():
            target = out / bundle
            lines = joined.count(b"\n")
            size = f"{count} parts, {lines} lines"
            current = target.exists() and target.read_bytes() == joined
            if args.check:
                if current:
                    print(f"{_shown(target)} is the join of its parts ({size})")
                elif not target.exists():
                    print(f"{_shown(target)} is missing; run this without "
                          "--check to create it")
                    stale += 1
                else:
                    print(explain(bundle, joined, target.read_bytes(), src, out))
                    stale += 1
            elif current:
                # Left alone rather than rewritten with the same bytes: a
                # run that changes nothing should touch nothing.
                print(f"{_shown(target)} is already the join of its parts ({size})")
            else:
                out.mkdir(parents=True, exist_ok=True)
                write_atomically(target, joined)
                print(f"wrote {_shown(target)} ({size})")
        return 1 if stale or refused else 0
    except PartsError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
