
  /* ================================================================== signing
   * groundwater/signing.py (PLAN.md step 8.2): signed statements. What a
   * person decided, in a text that can be checked against their key by
   * anyone, with no network. This is the part both engines share: how a
   * statement is written so that both write the same bytes, how it is read
   * back (strictly: a text the toolkit did not write is not read at all),
   * how a signature over it is checked, and how a signer is placed against
   * the list of keys an organisation publishes. signing.py says what a
   * signature shows and what it does not; the rules here are its own, rule
   * for rule, and the parity suite holds the two to each other.
   *
   * Making a signature is the app's work, with Web Crypto, which answers
   * only asynchronously and only in a secure context. Checking one is
   * written out here, synchronously, so that it works wherever the engine
   * does: from a laptop's disk, on a LAN address, in a worker, under Node.
   * It is verification only, of public values, so it need not run in
   * constant time. */

  var SIGNED_FORMAT = 'groundwater-toolkit signed statement';
  var MEMBERS_FORMAT = "groundwater-toolkit members' keys";
  var SIGNING_VERSION = 1;
  /* the largest whole number a statement holds: above it the two engines'
   * readers stop agreeing (a number here stops being exact at 2**53) */
  var SIGNING_MAX_NUMBER = 999999999;
  /* the longest text read, in bytes */
  var SIGNING_MAX_BYTES = 200000;
  var SIGNING_NAME = /^[a-z][a-z0-9_]{0,39}$/;
  var SIGNING_KEY = /^04[0-9a-f]{128}$/;
  var SIGNING_SIGNATURE = /^[0-9a-f]{128}$/;
  var SIGNING_KEY_ID = /^[0-9a-f]{64}$/;
  var SIGNED_KEYS = 'format,version,statement,key,signature';
  var MEMBERS_KEYS = 'format,version,organisation,issued_on,members';
  var MEMBER_KEYS = 'name,role,key,valid_from,valid_to,withdrawn';

  /* ---- the curve -----------------------------------------------------
   * NIST P-256 (secp256r1): y^2 = x^3 - 3x + b over the field of p, with a
   * group of prime order n generated by (gx, gy). FIPS 186-4, D.1.2.3.
   *
   * The numbers are whole numbers of 256 bits, which here are BigInt. They
   * are made by calling BigInt, never written as literals (123n): a browser
   * too old to have them would refuse to load the whole engine for one
   * literal, where this way it loads and says that it cannot check a
   * signature. */
  /** @type {Rec|null} */
  var P256 = null;

  /** The curve's numbers, or null where this browser has no whole numbers
   * long enough.
   * @returns {Rec|null} */
  function p256Curve() {
    if (P256) return P256;
    if (typeof BigInt !== 'function') return null;
    var big = BigInt;
    P256 = {
      zero: big(0), one: big(1), two: big(2), three: big(3), four: big(4), eight: big(8),
      p: big('0xffffffff00000001000000000000000000000000ffffffffffffffffffffffff'),
      n: big('0xffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551'),
      b: big('0x5ac635d8aa3a93e7b3ebbd55769886bc651d06b0cc53b0f63bce3c3e27d2604b'),
      gx: big('0x6b17d1f2e12c4247f8bce6e563a440f277037d812deb33a0f4a13945d898c296'),
      gy: big('0x4fe342e2fe1a7f9b8ee7eb4a7c0f9e162bce33576b315ececbb6406837bf51f5'),
    };
    return P256;
  }

  /** Whether signatures can be checked here: false only in a browser with
   * no BigInt.
   * @returns {boolean} */
  function canCheckSignatures() {
    return p256Curve() !== null;
  }

  /** @param {*} a @param {*} m */
  function bigMod(a, m) {
    var r = a % m;
    return r < m - m ? r + m : r;
  }

  /** The inverse of a modulo m, by Euclid's algorithm.
   * @param {*} a @param {*} m */
  function bigInverse(a, m) {
    var zero = m - m;
    var t = zero, nextT = zero + /** @type {*} */ (p256Curve()).one;
    var r = m, nextR = bigMod(a, m);
    while (nextR !== zero) {
      var q = r / nextR;
      var hold = t - q * nextT;
      t = nextT;
      nextT = hold;
      hold = r - q * nextR;
      r = nextR;
      nextR = hold;
    }
    return bigMod(t, m);
  }

  /* Points are kept as [X, Y, Z] with x = X/Z^2 and y = Y/Z^3, so that
   * adding two costs no division; null is the point at infinity. */
  /** @param {*} point @param {Rec} c */
  function p256Double(point, c) {
    if (!point || point[1] === c.zero) return null;
    var X = point[0], Y = point[1], Z = point[2];
    var YY = bigMod(Y * Y, c.p), S = bigMod(c.four * X * YY, c.p), ZZ = bigMod(Z * Z, c.p);
    var M = bigMod(c.three * (X - ZZ) * (X + ZZ), c.p);
    var X3 = bigMod(M * M - c.two * S, c.p);
    return [X3, bigMod(M * (S - X3) - c.eight * YY * YY, c.p), bigMod(c.two * Y * Z, c.p)];
  }

  /** @param {*} a @param {*} b @param {Rec} c */
  function p256Add(a, b, c) {
    if (!a) return b;
    if (!b) return a;
    var Z1Z1 = bigMod(a[2] * a[2], c.p), Z2Z2 = bigMod(b[2] * b[2], c.p);
    var U1 = bigMod(a[0] * Z2Z2, c.p), U2 = bigMod(b[0] * Z1Z1, c.p);
    var S1 = bigMod(a[1] * b[2] * Z2Z2, c.p), S2 = bigMod(b[1] * a[2] * Z1Z1, c.p);
    if (U1 === U2) return S1 === S2 ? p256Double(a, c) : null;
    var H = bigMod(U2 - U1, c.p), R = bigMod(S2 - S1, c.p);
    var HH = bigMod(H * H, c.p), HHH = bigMod(H * HH, c.p), V = bigMod(U1 * HH, c.p);
    var X3 = bigMod(R * R - HHH - c.two * V, c.p);
    return [X3, bigMod(R * (V - X3) - S1 * HHH, c.p), bigMod(H * a[2] * b[2], c.p)];
  }

  /** k times a point, by doubling and adding.
   * @param {*} k @param {*} point @param {Rec} c */
  function p256Times(k, point, c) {
    var total = null;
    while (k !== c.zero) {
      if (k % c.two === c.one) total = p256Add(total, point, c);
      point = p256Double(point, c);
      k = k / c.two;
    }
    return total;
  }

  /** Whether a signature (128 hexadecimal digits, r || s) is the ECDSA
   * P-256 / SHA-256 signature of a message under a public key (130
   * hexadecimal digits: 04, x, y). False for anything that is not a key on
   * the curve or a signature in range (signing.py verify_p256); null where
   * this browser cannot check one at all.
   * @param {*} key
   * @param {string|Uint8Array} message text (its UTF-8 bytes are signed) or the bytes
   * @param {*} signature
   * @returns {boolean|null} */
  function verifyP256(key, message, signature) {
    var c = p256Curve();
    if (!c) return null;
    if (typeof key !== 'string' || !SIGNING_KEY.test(key) || typeof signature !== 'string' ||
        !SIGNING_SIGNATURE.test(signature) ||
        !(typeof message === 'string' || ArrayBuffer.isView(message))) return false;
    var big = BigInt;
    var x = big('0x' + key.slice(2, 66)), y = big('0x' + key.slice(66));
    /* a point that is not on the curve is not a key: without this check a
     * made-up point can be chosen to pass for any message */
    if (x >= c.p || y >= c.p ||
        bigMod(y * y - (x * x * x - c.three * x + c.b), c.p) !== c.zero) return false;
    var r = big('0x' + signature.slice(0, 64)), s = big('0x' + signature.slice(64));
    if (r < c.one || r >= c.n || s < c.one || s >= c.n) return false;
    var digest = big('0x' + sha256Hex(message));
    var w = bigInverse(s, c.n);
    var point = p256Add(p256Times(bigMod(digest * w, c.n), [c.gx, c.gy, c.one], c),
      p256Times(bigMod(r * w, c.n), [x, y, c.one], c), c);
    if (!point || point[2] === c.zero) return false;
    var inverse = bigInverse(point[2], c.p);
    return bigMod(bigMod(point[0] * inverse * inverse, c.p), c.n) === r;
  }

  /** @param {string} hex @returns {Uint8Array} */
  function hexBytes(hex) {
    var bytes = new Uint8Array(hex.length / 2);
    for (var i = 0; i < bytes.length; i += 1) bytes[i] = parseInt(hex.slice(2 * i, 2 * i + 2), 16);
    return bytes;
  }

  /** What a statement calls a key: the SHA-256 of the public point's 65
   * bytes, as hexadecimal. Blank for anything that is not a key.
   * @param {*} key
   * @returns {string} */
  function keyId(key) {
    if (typeof key !== 'string' || !SIGNING_KEY.test(key)) return '';
    return sha256Hex(hexBytes(key));
  }

  /** A key's identifier as people read it out: its first 80 bits, in five
   * groups of four (signing.py key_code).
   * @param {*} identifier
   * @returns {string} */
  function keyCode(identifier) {
    if (typeof identifier !== 'string' || !SIGNING_KEY_ID.test(identifier)) return '';
    var head = identifier.slice(0, 20).toUpperCase();
    return [0, 4, 8, 12, 16].map(function (i) { return head.slice(i, i + 4); }).join('-');
  }

  /* ---- the text of a statement ----------------------------------------- */

  /** @param {*} value */
  function signingText(value) {
    return typeof value === 'string' && manifestText(value) === value;
  }

  /** @param {*} value */
  function signingWhole(value) {
    return typeof value === 'number' && Number.isInteger(value) && value >= 0 &&
      value <= SIGNING_MAX_NUMBER;
  }

  /** The value if it is a statement as the toolkit writes one, else null
   * (signing.py clean_statement): named values, `says` first and not blank,
   * each a clean text, a whole number in range, a list of clean texts, or
   * named clean texts.
   * @param {*} value
   * @returns {Rec|null} */
  function cleanStatement(value) {
    if (!isPlainObject(value)) return null;
    var names = Object.keys(value);
    if (!names.length || names[0] !== 'says' || !signingText(value.says) || !value.says) return null;
    for (var i = 0; i < names.length; i += 1) {
      var item = value[names[i]];
      if (!SIGNING_NAME.test(names[i])) return null;
      if (signingText(item) || signingWhole(item)) continue;
      if (Array.isArray(item) && item.every(signingText)) continue;
      if (isPlainObject(item) && Object.keys(item).every(function (key) {
        return SIGNING_NAME.test(key) && signingText(item[key]);
      })) continue;
      return null;
    }
    return value;
  }

  /** @param {*} value @returns {string} */
  function signingWritten(value) {
    return JSON.stringify(value, null, 2) + '\n';
  }

  /** The text of a statement: what is signed, byte for byte, in both
   * engines. Throws for anything that is not a statement, since a text
   * that cannot be read back must not be signed.
   * @param {*} statement
   * @returns {string} */
  function statementText(statement) {
    if (cleanStatement(statement) === null) {
      throw new Error('signing: this is not a statement the toolkit writes');
    }
    return signingWritten(statement);
  }

  /** What a JSON text holds, or undefined for anything the toolkit would
   * not have written: not text, too long, not JSON.
   * @param {*} text */
  function signingLoaded(text) {
    if (typeof text !== 'string') return undefined;
    try {
      if (utf8Encode(text).length > SIGNING_MAX_BYTES) return undefined;
      return JSON.parse(text);
    } catch (err) {
      return undefined;
    }
  }

  /** The statement a text holds, or null unless the text is exactly what
   * statementText writes for it.
   * @param {*} text
   * @returns {Rec|null} */
  function readStatement(text) {
    var statement = cleanStatement(signingLoaded(text));
    return statement !== null && signingWritten(statement) === text ? statement : null;
  }

  /* ---- a signed statement ---------------------------------------------- */

  /** The file a signed statement is kept in: what it is, the statement, the
   * public key and the signature. Throws for a statement, key or signature
   * that is not one.
   * @param {*} statement
   * @param {*} key
   * @param {*} signature
   * @returns {string} */
  function signedText(statement, key, signature) {
    if (cleanStatement(statement) === null) {
      throw new Error('signing: this is not a statement the toolkit writes');
    }
    if (typeof key !== 'string' || !SIGNING_KEY.test(key)) {
      throw new Error('signing: this is not a public key');
    }
    if (typeof signature !== 'string' || !SIGNING_SIGNATURE.test(signature)) {
      throw new Error('signing: this is not a signature');
    }
    return signingWritten({ format: SIGNED_FORMAT, version: SIGNING_VERSION,
      statement: statement, key: key, signature: signature });
  }

  /** What a signed statement's file holds ({statement, key, signature}), or
   * null unless the text is exactly what signedText writes. Reading says
   * nothing of whether the signature holds: checkSigned does.
   * @param {*} text
   * @returns {Rec|null} */
  function readSigned(text) {
    var held = signingLoaded(text);
    if (!isPlainObject(held) || Object.keys(held).join(',') !== SIGNED_KEYS) return null;
    if (held.format !== SIGNED_FORMAT || held.version !== SIGNING_VERSION) return null;
    var again;
    try {
      again = signedText(held.statement, held.key, held.signature);
    } catch (err) {
      return null;
    }
    if (again !== text) return null;
    return { statement: held.statement, key: held.key, signature: held.signature };
  }

  /* ---- the organisation's members -------------------------------------- */

  /** @param {*} value */
  function dayOrBlank(value) {
    return value === '' || (typeof value === 'string' && trimField(value) === value &&
      isoDay(value) !== null);
  }

  /** @param {*} value @returns {Rec|null} */
  function cleanMembers(value) {
    if (!isPlainObject(value) || Object.keys(value).join(',') !== MEMBERS_KEYS) return null;
    if (value.format !== MEMBERS_FORMAT || value.version !== SIGNING_VERSION) return null;
    /* a list with no organisation's name on it is nobody's list */
    if (!signingText(value.organisation) || !value.organisation) return null;
    if (value.issued_on === '' || !dayOrBlank(value.issued_on)) return null;
    if (!Array.isArray(value.members)) return null;
    /** @type {Record<string, boolean>} */
    var seen = {};
    for (var i = 0; i < value.members.length; i += 1) {
      var member = value.members[i];
      if (!isPlainObject(member) || Object.keys(member).join(',') !== MEMBER_KEYS) return null;
      if (!signingText(member.name) || !member.name || !signingText(member.role)) return null;
      if (typeof member.key !== 'string' || !SIGNING_KEY.test(member.key)) return null;
      /* a date that is not one is not read as "no date": the file is refused */
      if (!dayOrBlank(member.valid_from) || !dayOrBlank(member.valid_to) ||
          !dayOrBlank(member.withdrawn)) return null;
      /* one key, one member: listed twice, which of the two is it? */
      if (seen[member.key]) return null;
      seen[member.key] = true;
    }
    return value;
  }

  /** The text of an organisation's file of its members' keys. Throws for
   * anything that is not one.
   * @param {*} members
   * @returns {string} */
  function membersText(members) {
    if (cleanMembers(members) === null) {
      throw new Error("signing: this is not a members' file the toolkit writes");
    }
    return signingWritten(members);
  }

  /** What a members' file holds, or null unless the text is exactly what
   * membersText writes (signing.py read_members).
   * @param {*} text
   * @returns {Rec|null} */
  function readMembers(text) {
    var members = cleanMembers(signingLoaded(text));
    return members !== null && signingWritten(members) === text ? members : null;
  }

  /** The code a members' file is known by: of the SHA-256 of its text, the
   * first 80 bits in five groups of four, to compare by voice or on paper.
   * @param {*} text
   * @returns {string} */
  function membersCode(text) {
    return readMembers(text) === null ? '' : keyCode(sha256Hex(text));
  }

  /** Where a key stands in a members' file on a day (signing.py
   * signer_standing): not_checked with no file; not_listed; withdrawn,
   * whatever day the statement claims; out_of_dates; else listed.
   * @param {*} members what readMembers gave
   * @param {*} identifier the key's identifier
   * @param {*} [day] the day the statement says it was signed
   * @returns {{standing: string, member: Rec|null}} */
  function signerStanding(members, identifier, day) {
    if (cleanMembers(members) === null) return { standing: 'not_checked', member: null };
    var member = null;
    for (var i = 0; i < members.members.length && !member; i += 1) {
      if (keyId(members.members[i].key) === identifier) member = members.members[i];
    }
    if (!member) return { standing: 'not_listed', member: null };
    if (member.withdrawn) return { standing: 'withdrawn', member: member };
    if (member.valid_from || member.valid_to) {
      var on = typeof day === 'string' && dayOrBlank(day) ? day : '';
      if (!on || (member.valid_from && on < member.valid_from) ||
          (member.valid_to && on > member.valid_to)) {
        return { standing: 'out_of_dates', member: member };
      }
    }
    return { standing: 'listed', member: member };
  }

  /* ---- checking --------------------------------------------------------- */

  /** Check a signed statement's file, and its signer against a members'
   * file where one is given, its text (signing.py check_signed). verdict is
   * not_a_statement, does_not_hold or holds; or cannot_check in a browser
   * with no way to check a signature, which the Python engine never says.
   * @param {*} text
   * @param {*} [membersFile]
   * @returns {Rec} */
  function checkSigned(text, membersFile) {
    /** @type {Rec} */
    var out = { verdict: 'not_a_statement', statement: null, key: '', code: '',
      standing: 'not_checked', member: null, file_code: '', lines: [] };
    var signed = readSigned(text);
    if (signed === null) {
      out.lines = [phrase('signing.not_a_statement')];
      return out;
    }
    var statement = signed.statement;
    var identifier = keyId(signed.key);
    out.statement = statement;
    out.key = identifier;
    out.code = keyCode(identifier);
    /* the statement names its key, so that the signature binds the key */
    var holds = statement.key === identifier
      ? verifyP256(signed.key, signingWritten(statement), signed.signature) : false;
    if (holds === null) {
      out.verdict = 'cannot_check';
      out.lines = ['This browser is too old to check a signature. Check it in another ' +
        'browser, or with the command "groundwater signature".'];
      return out;
    }
    if (!holds) {
      out.verdict = 'does_not_hold';
      out.lines = [phrase('signing.does_not_hold')];
      return out;
    }
    out.verdict = 'holds';
    var lines = [phrase('signing.holds', { code: out.code })];
    var at = statement.at;
    if (typeof at === 'string' && at) lines.push(phrase('signing.time_is_a_claim', { at: at }));
    var given = membersFile !== null && membersFile !== undefined;
    var members = given ? readMembers(membersFile) : null;
    if (given && members === null) {
      lines.push(phrase('signing.members_unreadable'));
    } else if (members === null) {
      lines.push(phrase('signing.standing_not_checked'));
    } else {
      var placed = signerStanding(members, identifier, typeof at === 'string' ? at.slice(0, 10) : '');
      out.standing = placed.standing;
      out.member = placed.member;
      out.file_code = membersCode(membersFile);
      if (!placed.member) {
        lines.push(phrase('signing.standing_not_listed',
          { organisation: members.organisation, file: out.file_code }));
      } else {
        var sentence = { listed: 'signing.standing_listed',
          withdrawn: 'signing.standing_withdrawn',
          out_of_dates: 'signing.standing_out_of_dates' }[placed.standing];
        lines.push(phrase(/** @type {string} */ (sentence), { name: placed.member.name,
          role: placed.member.role || phrase('signing.no_role'),
          organisation: members.organisation, file: out.file_code }));
      }
    }
    out.lines = lines;
    return out;
  }

  Object.assign(C, {
    SIGNED_FORMAT: SIGNED_FORMAT, MEMBERS_FORMAT: MEMBERS_FORMAT,
    canCheckSignatures: canCheckSignatures, verifyP256: verifyP256, keyId: keyId,
    keyCode: keyCode, cleanStatement: cleanStatement, statementText: statementText,
    readStatement: readStatement, signedText: signedText, readSigned: readSigned,
    membersText: membersText, readMembers: readMembers, membersCode: membersCode,
    signerStanding: signerStanding, checkSigned: checkSigned,
  });
